import { careCards } from "../../constants";

/* ═════════════════════ ПАМЯТКА ПО ОБРАЩЕНИЮ С ШАРАМИ ═════════════════════

   Пять правил в bento-сетке 4×2. Одна карточка занимает левую половину
   блока целиком (две колонки на два ряда) и показывает иллюстрацию
   крупно; четыре квадратные встают справа в два ряда по две.

     ┌───────────────┬───────┬───────┐
     │               │ питом.│ ВАЖНО │
     │  за ленту     ├───────┼───────┤
     │               │  ЭКО  │ салон │
     └───────────────┴───────┴───────┘

   Плашки разведены по ДИАГОНАЛИ квадрата (порядок карточек задан в
   constants.ts). Стояли обе в правом столбце — и он перевешивал.

   Правил стало пять, а не шесть: мороз и солнце были двумя карточками,
   хотя правило одно — шару вредят перепады температуры с любой стороны.
   Вместе они и читаются как одно правило, и сетка сходится без пустой
   ячейки.

   ЧЕТЫРЕ КОЛОНКИ ВКЛЮЧАЮТСЯ ТОЛЬКО С 1200px, а не с md (768). Самый
   длинный заголовок — «Берегите от перепадов», 217px при 17px полужирном
   Montserrat. Чтобы он держался в одну строку, карточке нужно 267px
   ширины, а четырём таким плюс зазоры — 1176px окна. На планшете четыре
   колонки давали карточку в 178px: заголовки рвались надвое, карточки
   вытягивались до 322px, и большая рядом с ними получала 255px пустоты.
   До 1200px работает та же раскладка, что на телефоне: большая карточка
   во всю ширину, четыре квадратные по две в ряд. Ширина сетки там
   поджата до 46rem, иначе карточки расплываются в полосы.

   ПОРЯДОК ЧТЕНИЯ ОДИН У ВСЕХ: иллюстрация → заголовок → описание.
   Большая карточка раньше шла наоборот (заголовок → текст → связка) и
   выглядела чужой среди остальных.

   Размер картинки считается от ВИДИМОГО содержимого, а не от кадра файла.
   У PNG вокруг шара свои прозрачные поля — от 20% кадра до 74%, — и
   «вписать по файлу» означало бы, что один значок занимает квадрат
   целиком, а соседний болтается в нём вдвое мельче.
   ───────────────────────────────────────────────────────────────────────── */

// Карточки выходят РЯДАМИ: сначала верхний ряд целиком, потом следующий.
const REVEAL_MS = 720; // длительность появления карточки
const ROW_MS = 280; // пауза между рядами, если оба вышли на экран разом
const LAYER_MS = 90; // сдвиг между слоями внутри карточки
const EASE = "cubic-bezier(0.33, 0, 0.2, 1)"; // плавный старт и плавное торможение

/* Габариты, в которые вписывается ВИДИМОЕ содержимое картинки.

   Считаем именно от содержимого, а не от кадра файла. У PNG вокруг шара
   свои прозрачные поля — от 61% кадра до 93%, — и «вписать по файлу»
   означало бы, что одна иллюстрация занимает отведённое место целиком, а
   соседняя болтается в нём вдвое мельче.

   Габарит один на все квадратные карточки — 72×72, как и сам контейнер
   под значок. Внутри него каждая картинка ещё поправляется на свою
   оптическую массу (поле k, см. constants.ts): габарит уравнивает
   размер, k — количество краски.

   Пара стоит мельче: две картинки должны уместиться по ширине того же
   квадрата, да ещё с наклоном ±7°. Ширина 32, а не 33: 33 + 33 + зазор 12
   давало 78px в коробке 72 — пара вылезала из неё на 3px с каждой
   стороны. Теперь 32 + 32 + зазор 8 = ровно 72.

   Большой карточке габарит в пикселях не нужен: связка меряется долей
   ширины карточки с потолком в 380px, а высоту ей задают собственные
   пропорции. */
const SOLO = { h: 72, w: 72 };
const PAIR = { h: 62, w: 32 };

type Img = {
  src: string;
  fx: number;
  fy: number;
  fw: number;
  fh: number;
  ar: number;
  k?: number;
};

type Card = (typeof careCards)[number];

/** Картинка, обрезанная по своему содержимому: прозрачные поля уходят за
    край обёртки, а сама обёртка и есть видимый шар.

    shade — собственная тень по силуэту. Нужна светлым картинкам на
    светлой подложке; на наведении её перебивает более плотная тень из
    index.css (правило там специфичнее утилиты). */
const Cropped = ({ img, shade }: { img: Img; shade?: boolean }) => (
  <img
    src={img.src}
    alt=""
    aria-hidden="true"
    loading="lazy"
    className={`absolute max-w-none select-none ${
      shade ? "drop-shadow-[0_1px_2px_rgba(107,78,129,0.35)]" : ""
    }`}
    style={{
      width: `${100 / img.fw}%`,
      height: `${100 / img.fh}%`,
      left: `${(-img.fx / img.fw) * 100}%`,
      top: `${(-img.fy / img.fh) * 100}%`,
    }}
  />
);

/** СЦЕНА: несколько картинок, расставленных по коробке абсолютом.

    Нужна там, где значок — не один предмет, а маленькая композиция:
    у «перепадов» это шар посередине, снежинка слева снизу и солнце
    справа сверху. Обычный Art выстраивает картинки В РЯД и для такого
    не годится.

    Координаты — доли коробки в процентах, высота считается из пропорций
    содержимого. Каждый элемент получает memo-figure, поэтому вся сцена
    оживает на наведении разом, как и одиночные значки. */
const Scene = ({
  scene,
}: {
  scene: readonly {
    img: Img;
    left: number;
    top: number;
    w: number;
    shade?: boolean;
  }[];
}) => (
  /* self-stretch: коробка значка выстроена по нижнему краю (items-end), и
     без него сцена схлопнулась бы в ноль — все её элементы лежат
     абсолютом и своей высоты не дают. */
  <div className="relative w-full self-stretch">
    {scene.map(({ img, left, top, w, shade }, i) => (
      <div
        key={`${img.src}-${i}`}
        className="memo-figure absolute"
        style={{
          left: `${left}%`,
          top: `${top}%`,
          width: `${w}%`,
          aspectRatio: `${img.ar}`,
        }}
      >
        <Cropped img={img} shade={shade} />
      </div>
    ))}
  </div>
);

/** Ряд картинок карточки, вписанных в отведённый габарит.

    items-end justify-start — все значки садятся на нижнюю кромку своей
    коробки у левого края. По центру они стояли на разной высоте:
    вписанные по длинной стороне картинки имеют разные пропорции, и
    нижние края расходились до 14px. Общая линия важнее центровки. */
const Art = ({ card, box }: { card: Card; box: typeof SOLO }) => (
  <div className="flex items-end justify-start gap-2">
    {card.images.map((img, i) => {
      // Вписываем по той стороне, которая упирается первой
      const byWidth = img.ar > box.w / box.h;
      const k = img.k ?? 1; // поправка на оптическую массу
      const w = (byWidth ? box.w : box.h * img.ar) * k;
      const h = (byWidth ? box.w / img.ar : box.h) * k;

      return (
        <div
          key={img.src}
          /* без overflow-hidden: при повороте ±7° и при подъёме на
             наведении клипирование срезало бы шар по краям.
             memo-figure — левитация, см. index.css. */
          className="memo-figure relative"
          style={{
            width: w,
            height: h,
            transform:
              card.images.length > 1
                ? `rotate(${i === 0 ? -7 : 7}deg)`
                : undefined,
          }}
        >
          <Cropped img={img} />
        </div>
      );
    })}
  </div>
);

/* Общий вид карточки: матовое стекло. Размытие подложки — только с md:
   стекло имеет смысл там, где под ним есть что размывать, а на телефоне
   пятна за карточками мелкие и разницы не видно, зато слои размытия
   платятся каждым кадром прокрутки. */
/* Тень КОРОТКАЯ, а контур настоящий. Прежняя тень уходила на 36px и на
   светлом фоне не читалась вовсе — только мылила края карточки. Тонкая
   линия очерчивает форму честнее, а тень в 6px просто отрывает карточку
   от фона. Цвет контура задаётся вместе с подложкой (tone): у розовых
   карточек он свой, иначе розовое поле обводилось бы лиловым. */
const CARD =
  "memo-card flex h-full flex-col rounded-3xl border " +
  "shadow-[0_2px_6px_rgba(45,36,51,0.05)] " +
  "transition duration-500 ease-out md:backdrop-blur-[16px] " +
  "md:hover:-translate-y-1.5 " +
  "md:hover:shadow-[0_10px_20px_rgba(45,36,51,0.10)]";

export const CareCards = () => {
  const cardRefs = useRef<(HTMLDivElement | null)[]>([]);

  /* ПОЯВЛЕНИЕ ПО РЯДАМ.

     Наблюдаем каждую карточку отдельно, но задержку назначаем не ей, а её
     РЯДУ. Ряд определяем по фактической геометрии — offsetTop, — а не по
     номеру карточки: в bento-сетке ряды разной длины, и «каждые столько-то
     подряд» означало бы совсем не то, что видит глаз. */
  const [delays, setDelays] = useState<Record<number, number>>({});
  const isShown = (i: number) => i in delays;

  useEffect(() => {
    const all = careCards.map((_, i) => i);

    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      setDelays(Object.fromEntries(all.map((i) => [i, 0])));
      return;
    }

    const io = new IntersectionObserver(
      (entries) => {
        const hit = entries
          .filter((e) => e.isIntersecting)
          .map((e) => {
            const el = e.target as HTMLElement;
            // Округляем до 8px: карточки одного ряда стоят на одной линии,
            // но дробные значения после масштабирования страницы могут
            // разойтись на пиксель-другой.
            return {
              i: Number(el.dataset.card),
              row: Math.round(el.offsetTop / 8),
            };
          });
        if (!hit.length) return;

        const rows = [...new Set(hit.map((h) => h.row))].sort((a, b) => a - b);

        setDelays((prev) => {
          const next = { ...prev };
          hit.forEach(({ i, row }) => {
            if (!(i in next)) next[i] = rows.indexOf(row) * ROW_MS;
          });
          return next;
        });

        // Показанную карточку больше не наблюдаем: эффект одноразовый
        hit.forEach(({ i }) => {
          const el = cardRefs.current[i];
          if (el) io.unobserve(el);
        });
      },
      { threshold: 0.15 },
    );

    cardRefs.current.forEach((el) => el && io.observe(el));
    return () => io.disconnect();
  }, []);

  // общий помощник: плавный выход слоя с собственной задержкой
  const layer = (idx: number, step: number, hidden: string) => ({
    opacity: isShown(idx) ? 1 : 0,
    transform: isShown(idx) ? "none" : hidden,
    transition: `opacity ${REVEAL_MS}ms ${EASE}, transform ${REVEAL_MS}ms ${EASE}`,
    transitionDelay: isShown(idx) ? `${delays[idx] + step}ms` : "0ms",
  });

  return (
    /* min-h + justify-center: на широком экране блок занимает почти весь
       экран и стоит по центру, а не жмётся к верхнему краю. На телефоне
       высота обычная — 85vh там означало бы полтора экрана пустоты вокруг
       ленты карточек.

       ВЕРХНИЙ ПАДИНГ 84px, а не 40. Шапка сайта прилипшая и высотой ровно
       73px на любой ширине окна. Надстрочка «бережно» стояла на 40-й
       строке секции, то есть целиком уезжала под шапку, стоило секции
       дойти до верха экрана: наружу торчал только хвост «р», который у
       рукописного шрифта уходит на 0.667em ниже базовой линии, — он и
       читался как обрезанный розовый штрих неизвестного происхождения.
       84 = 73 шапки + 11 воздуха. */
    <section className="relative flex flex-col justify-center overflow-hidden bg-[#F8F4F9] px-6 pt-[5.25rem] pb-12 md:min-h-[85vh] md:pb-10">
      {/* ЦВЕТНЫЕ ПЯТНА ПОД КАРТОЧКАМИ. Без них стекло не работает:
          полупрозрачный белый поверх ровной заливки — это просто белый. */}
      <div aria-hidden="true" className="pointer-events-none absolute inset-0">
        <div className="absolute -top-24 -left-20 h-[460px] w-[460px] rounded-full bg-[#D9A7C0]/28 blur-[110px]" />
        <div className="absolute top-1/4 -right-24 h-[520px] w-[520px] rounded-full bg-[#6B4E81]/18 blur-[130px]" />
        <div className="absolute -bottom-28 left-1/4 h-[440px] w-[440px] rounded-full bg-[#C9A6E0]/24 blur-[120px]" />
      </div>

      <div className="relative z-10 mx-auto w-full max-w-[76rem]">
        <p className="font-miana pb-[0.5em] text-center text-2xl leading-none text-[#C46B8A] md:text-3xl">
          бережно
        </p>

        <h2 className="text-center text-[2rem] leading-[1.1] font-semibold tracking-[-0.015em] text-[#2D2433] md:text-[2.6rem]">
          Памятка по обращению с шарами
        </h2>

        {/* 34ch + text-balance. При max-w-xl (576px) строка рвалась так, что
            «долго!» оставалось одно на второй строке. Балансировщик делит
            текст на строки поровну, а узкая мера не даёт ему выстроиться
            в одну длинную. */}
        <p className="mx-auto mt-2.5 max-w-[34ch] text-center text-base leading-relaxed font-medium text-balance text-[#5A4D66] md:text-[17px]">
          Несколько простых правил и шарики будут летать очень долго!
        </p>

        {/* СЕТКА.

            До 1200px — две колонки: большая карточка во всю ширину,
            четыре квадратные под ней по две в ряд. Ширина поджата до
            46rem, иначе на планшете карточки растягиваются в полосы с
            значком в углу и двумя строчками текста.

            С 1200px — четыре колонки. grid-auto-rows: 1fr держит оба ряда
            одной высоты: без него нижний ряд подстроился бы под свой
            текст, а большая карточка тянулась бы на два разных ряда и
            выглядела бы кривой. В двухколоночной раскладке 1fr не нужен —
            там ряды естественной высоты, и большая карточка ничего не
            растягивает.

            items-stretch (умолчание грида): карточка занимает свою ячейку
            целиком, поэтому все четыре квадратные равны по высоте, сколько
            бы строк ни было в описании. */}
        <div className="mx-auto mt-8 grid max-w-[46rem] grid-cols-2 gap-4 md:gap-5 min-[1200px]:max-w-none min-[1200px]:grid-cols-4 min-[1200px]:[grid-auto-rows:1fr]">
          {careCards.map((card, idx) => {
            const hero = "hero" in card && card.hero;
            const accent = "accent" in card && card.accent;
            const tag = "tag" in card ? card.tag : undefined;

            /* ДВА ТОНА, НЕ ТРИ. Было три — белый, розовый и лиловый, — и
               пять карточек на три оттенка читались как случайность.
               Теперь тон отвечает ровно на один вопрос: есть плашка или
               нет. Какая именно плашка, говорит она сама.

               Лиловый ушёл именно он: подложка секции сама лилово-сиреневая
               (#F8F4F9 плюс пятно #6B4E81), и лиловая карточка вставала на
               ней почти вплотную по цвету — разница по каналам выходила
               (1, −5, 6). У розовой на том же месте (13, 9, 6), а на полной
               непрозрачности (16, 11, 7): втрое заметнее. */
            const tone = tag
              ? "border-[#EFD4E0] bg-[#FBEFF5] md:hover:border-[#D9A7C0] md:hover:bg-[#FDF5F9]"
              : "border-[#E8DEEE] bg-white/75 md:hover:border-[#D9C6E4] md:hover:bg-white/90";

            return (
              /* Внешняя обёртка держит ПОЯВЛЕНИЕ и место в сетке,
                 внутренняя — наведение. Разделено намеренно: появление
                 пишет transform инлайном, а инлайновый стиль сильнее
                 классов — подъём при наведении на той же ноде просто не
                 сработал бы. */
              <div
                key={card.title}
                ref={(el) => {
                  cardRefs.current[idx] = el;
                }}
                data-card={idx}
                className={hero ? "col-span-2 min-[1200px]:row-span-2" : ""}
                style={{
                  opacity: isShown(idx) ? 1 : 0,
                  transform: isShown(idx)
                    ? "none"
                    : "translateY(20px) scale(0.98)",
                  transition: `opacity ${REVEAL_MS}ms ${EASE}, transform ${REVEAL_MS}ms ${EASE}`,
                  transitionDelay: isShown(idx) ? `${delays[idx]}ms` : "0ms",
                }}
              >
                {hero ? (
                  /* ── БОЛЬШАЯ КАРТОЧКА ──
                     Связка свисает с ВЕРХНЕЙ кромки, под ней воздух, внизу
                     заголовок и текст — тот же порядок чтения, что у
                     четырёх квадратных.

                     Прежде было наоборот: заголовок сверху, связка внизу
                     во всю ширину карточки. Она занимала 596×331 — 65%
                     высоты, — и именно она задавала высоту всей сетке:
                     карточке требовалось 505px там, где квадратным хватало
                     471.6, и лишние 33.5px грид раскидывал по двум рядам,
                     открывая дыру под каждым значком.

                     overflow-hidden обязателен: картинка нарисована
                     обрезанной по верхнему краю кадра и на наведении
                     подаётся ещё выше. */
                  <article
                    className={`${CARD} ${tone} overflow-hidden p-6 pt-0 md:p-8 md:pt-0`}
                  >
                    {/* Блок иллюстрации забирает весь излишек высоты
                        карточки (flex-1), а сама связка прижата к верхней
                        кромке (self-start) и упирается в неё. Отрицательные
                        поля гасят боковые падинги: связка меряется от
                        кромки до кромки, а не от текстовой колонки.

                        68% ширины с потолком 420px. Было 596×331 — узел
                        разъезжался в розовое пятно и обрывался нижней границей
                        карточки. Стало 420×233 — ровно вдвое меньше по площади.
                        Обрезка осталась только сверху, где читается как «связка
                        уходит за карточку»: так её и нарисовали, верхний край
                        шара срезан в самом файле (fy = 0). Узел виден целиком. */}
                    <div
                      className="-mx-6 flex justify-center md:-mx-8"
                      style={layer(
                        idx,
                        LAYER_MS,
                        "translateY(-10px) scale(0.96)",
                      )}
                    >
                      {/* Переворот по вертикали снят вместе с переносом
                          наверх. Связка нарисована СВИСАЮЩЕЙ — широкий бок
                          сверху, узел книзу, — и у верхней кромки это её
                          родное положение. Костыль .memo-figure--flip был
                          нужен только пока она стояла внизу. */}
                      <div
                        className="memo-figure relative w-[68%] max-w-[420px] self-start"
                        style={{ aspectRatio: `${card.images[0].ar}` }}
                      >
                        <Cropped img={card.images[0]} />
                      </div>
                    </div>

                    {/* Излишек высоты забирает ТЕКСТОВЫЙ блок и делит его
                        поровну сверху и снизу (flex-1 + justify-center).

                        Забирал блок иллюстрации — и весь излишек, 116px на
                        широком экране, собирался в одну белую полосу между
                        узлом и заголовком, при 32px под текстом. Теперь
                        разрывы почти равные, и текст стоит в нижней трети
                        карточки, а не приклеен к её кромке. На планшете и
                        телефоне излишка нет вовсе — там высота карточки
                        естественная, и блок ведёт себя как обычный. */}
                    <div className="mt-6 flex flex-1 flex-col justify-center">
                      <h3
                        className="text-[1.35rem] leading-tight font-bold tracking-[-0.015em] text-[#2D2433] md:text-2xl"
                        style={layer(idx, LAYER_MS * 2, "translateY(8px)")}
                      >
                        {card.title}
                      </h3>

                      <p
                        className="mt-3 max-w-md text-[15px] leading-[1.55] font-medium text-[#4A3A5C] md:text-base"
                        style={layer(idx, LAYER_MS * 3, "translateY(8px)")}
                      >
                        {card.description}
                      </p>

                      {/* ВЫХОД ИЗ ПАМЯТКИ В КАТАЛОГ.
                          Ссылка текстом, без плашки: рядом с описанием
                          правила кнопка с заливкой читалась бы как
                          «согласен», а не как переход.

                          Черта под текстом стоит СРАЗУ, а не появляется на
                          наведении: она и есть признак, что это ссылка, а
                          не просто подпись. На наведении темнеет и уезжает
                          стрелка. */}
                      <Link
                        to="/catalog"
                        className="group/link mt-5 inline-flex w-fit items-center gap-2 border-b border-[#6B4E81]/40 pb-0.5 text-[15px] font-bold text-[#6B4E81] transition-colors hover:border-[#513A6B] hover:text-[#513A6B] md:text-base"
                        style={layer(idx, LAYER_MS * 4, "translateY(8px)")}
                      >
                        Посмотреть каталог
                        <ArrowRight className="h-4 w-4 transition-transform duration-300 ease-out group-hover/link:translate-x-1" />
                      </Link>
                    </div>
                  </article>
                ) : (
                  /* ── КВАДРАТНАЯ КАРТОЧКА ──
                     gap-5 вместо mt-auto. mt-auto отрывал текст от значка и
                     прижимал к нижней кромке: пока высоту диктовала большая
                     карточка, между ними зияло 37px вместо 20. Теперь связка
                     «значок → заголовок → описание» стоит вплотную к верху с
                     постоянным шагом, а излишек, если он есть, остаётся
                     внизу.

                     relative — для плашки, которая лежит абсолютом в правом
                     верхнем углу. */
                  <article
                    className={`${CARD} ${tone} relative gap-5 p-5 md:p-6`}
                  >
                    {/* ПЛАШКА ВНЕ ПОТОКА. Стояла она в строке с
                        заголовком, и две карточки из четырёх получали
                        заголовок в две строки — заголовки соседей
                        разъезжались по вертикали на полсотни пикселей.
                        Теперь она занимает пустой угол справа от значка и
                        на поток не влияет вовсе. */}
                    {/* НА ТЕЛЕФОНЕ ПЛАШКА В ПОТОКЕ, А НЕ В УГЛУ.

                        Угол работает, пока карточка широкая: при 289px
                        значок занимает 24..96, плашка 183..265 — они не
                        встречаются. На 390px карточка сужается до 163, и
                        «ВАЖНО» (82px) начинается с 61-го пикселя, прямо
                        поверх значка: солнце в сцене «перепадов» стоит на
                        62..87 и уходило под плашку. Ни подвинуть значок,
                        ни ужать надпись некуда — 72 + 82 + отступы это уже
                        194px при ширине карточки 163.

                        Поэтому на узком экране плашка становится обычной
                        строкой сверху, а в угол уходит с sm, где место для
                        неё появляется. */}
                    {tag && (
                      <span
                        className={`w-fit rounded-full border px-2.5 py-0.5 text-[13px] font-bold tracking-[0.08em] uppercase sm:absolute sm:top-4 sm:right-4 ${
                          accent
                            ? "border-[#D9C2EA] bg-white/70 text-[#513A6B]"
                            : "border-[#EFD4E0] bg-white/70 text-[#A64D6C]"
                        }`}
                      >
                        {tag}
                      </span>
                    )}

                    {/* КВАДРАТ 72×72 ПОД ЗНАЧОК — один на все карточки.
                        items-end justify-start: картинки садятся на нижнюю
                        кромку коробки у левого края и встают на общую
                        линию. По центру их нижние края расходились до 14px,
                        и значки выглядели поставленными вразнобой. */}
                    <div
                      className="flex h-[72px] w-[72px] items-end justify-start"
                      style={layer(
                        idx,
                        LAYER_MS,
                        "translateY(8px) scale(0.92)",
                      )}
                    >
                      {"scene" in card && card.scene ? (
                        <Scene scene={card.scene} />
                      ) : (
                        <Art
                          card={card}
                          box={card.images.length > 1 ? PAIR : SOLO}
                        />
                      )}
                    </div>

                    <div>
                      <h3
                        className="text-[17px] leading-tight font-bold tracking-[-0.01em] text-[#2D2433]"
                        style={layer(idx, LAYER_MS * 2, "translateY(8px)")}
                      >
                        {card.title}
                      </h3>

                      <p
                        className="mt-1.5 text-[13px] leading-[1.45] font-medium text-[#4A3A5C]"
                        style={layer(idx, LAYER_MS * 3, "translateY(8px)")}
                      >
                        {card.description}
                      </p>
                    </div>
                  </article>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
};
