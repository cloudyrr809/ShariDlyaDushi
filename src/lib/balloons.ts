/**
 * Стили для картинки внутри бокса, у которого высота задана, а ширина
 * равна высоте × ar. Прозрачные поля при этом уходят ЗА пределы бокса, и
 * видимый шар занимает его ровно целиком — сколько бы пустоты ни было
 * вокруг рисунка в самом файле.
 */
export const balloonFit = (a: BalloonArt): React.CSSProperties => ({
  width: `${100 / a.fw}%`,
  height: `${100 / a.fh}%`,
  left: `${(-a.fx / a.fw) * 100}%`,
  top: `${(-a.fy / a.fh) * 100}%`,
});
