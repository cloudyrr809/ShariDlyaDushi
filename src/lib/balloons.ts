/* ──────────────────── ГЕОМЕТРИЯ ШАРОВ-КАРТИНОК ────────────────────

   У каждого PNG вокруг самого шара своя ширина прозрачных полей:
   содержимое занимает от 46% кадра (ballon2) до 93% (ballon3). Если
   задавать размер файлу, видимые шары отличаются вдвое — что и было в
   первых заходах и на плитках акций, и в памятке.

   Поэтому масштабируем не файл, а его непрозрачную часть:
     fx/fy — где начинается содержимое, в долях кадра;
     fw/fh — какую долю кадра оно занимает;
     ar    — соотношение сторон самого содержимого (ширина / высота).

   Значения сняты по альфа-каналу. ВНИМАНИЕ: они привязаны к конкретным
   файлам, и при замене любого ballon*.png их надо перемерить — иначе шар
   растянет по одной оси. Ровно это и случилось 31.08, когда файлы
   заменили на 1080×1080, а таблица осталась от прежних кадров.

   Таблица общая: до неё эти же числа были переписаны в Hero.tsx и
   Promotions.tsx по отдельности, и обновлять их приходилось в двух
   местах. В Hero своя копия пока осталась — там к ним добавлено
   положение узелка ленточки, которого больше нигде нет. */

