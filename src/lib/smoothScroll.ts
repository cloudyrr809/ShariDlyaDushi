import Lenis from "lenis";

/* ──────────────────────── ПЛАВНАЯ ПРОКРУТКА ────────────────────────

   Тот же «тягучий» скролл, что на augen.pro. Там он сделан на библиотеке
   Lenis — она перехватывает колесо мыши и трекпад и доводит страницу до
   новой позиции по инерции, вместо резкого шага браузера. Разметку это
   не трогает: просто плавнее едет.

   Настройки — как у augen: длительность добега 1.2 c и та же кривая
   замедления (expo-out). Тачскрин оставляем РОДНОЙ прокрутке
   (syncTouch: false) — на телефоне инерция уже своя, а перехват там
   только добавляет рывков.

   Экземпляр держим на уровне модуля: до него дотягивается ScrollToTop в
   main.tsx, чтобы переход между страницами и прыжок к якорю шли через ту
   же самую прокрутку, а не спорили с ней. */

let instance: Lenis | null = null;

/** До какого момента (performance.now()) следующее расхождение позиции —
    это НАШ собственный вызов scrollTo, а не посторонний drag ползунка.
    На уровне модуля, а не внутри startSmoothScroll: markOwnScroll()
    вызывают из других файлов, им нужен один общий счётчик. */
let ownScrollUntil = 0;

/** Текущий экземпляр Lenis или null, пока плавная прокрутка не запущена
    (не запускается при системной настройке «меньше движения»). */
export function getLenis(): Lenis | null {
  return instance;
}

/**
 * Помечает ближайшие ~2 секунды как «наш» программный скролл — сторож
 * ползунка (см. ниже) не должен принять его за постороннее движение
 * страницы и остановить.
 *
 * Вызывать НЕПОСРЕДСТВЕННО перед своим `getLenis()?.scrollTo(...)` —
 * переходом к якорю, возвратом к началу блока и подобным.
 */
export function markOwnScroll(): void {
  ownScrollUntil = performance.now() + 2000;
}

/**
 * Замораживает плавную прокрутку, пока открыт оверлей, и возвращает
 * функцию возобновления.
 *
 * Одного `body { overflow: hidden }` мало: Lenis двигает страницу сам и
 * про запрет на теле не знает — под открытым окном фон продолжал бы
 * ехать. Зовём рядом с той же блокировкой прокрутки, а возобновление
 * отдаём в cleanup эффекта.
 */
export function pauseSmoothScroll(): () => void {
  const lenis = instance;
  if (!lenis) return () => {};
  lenis.stop();
  return () => lenis.start();
}

/** Запускает плавную прокрутку и цикл кадров. Возвращает функцию
    остановки — её отдаём из useEffect как cleanup. */
export function startSmoothScroll(): () => void {
  if (typeof window === "undefined") return () => {};

  // «Меньше движения» — уважаем так же, как в Hero и счётчиках: оставляем
  // родную мгновенную прокрутку.
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    return () => {};
  }

  if (instance) return () => {};

  instance = new Lenis({
    duration: 1.2,
    easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
    smoothWheel: true,
    syncTouch: false,
    touchMultiplier: 1.5,
  });

  /* ─── ПОЛЗУНОК ПРОКРУТКИ ПРОТИВ ИНЕРЦИИ ───

     Пока Lenis доводит страницу после колеса (isScrolling === "smooth"),
     он игнорирует нативные scroll-события — так устроен его onNativeScroll:
     событие обрабатывается, только если isScrolling === false | "native".
     Стоило крутануть колесо и сразу схватить ползунок — и страница ехала
     не туда, куда её тянут: Lenis продолжал доводить свою анимацию поверх
     чужого движения.

     Как ловим: между кадрами страницу двигает только браузер. Если перед
     очередным кадром фактическая позиция разошлась с той, которую Lenis
     нарисовал в прошлом кадре, значит её сдвинули мимо него.

     ПОЧИНИТЬ ВЫЗОВОМ scrollTo(window.scrollY) — так было в первой версии
     этого сторожа — оказалось хуже, чем не чинить вовсе: scrollTo клэмпит
     цель по lenis.limit, а этот предел иногда отстаёт от настоящей высоты
     страницы (пока подгружаются шрифты, картинки или секции меняют
     высоту). Клэмп утаскивал экран НАЗАД, к устаревшему пределу, — и
     рождался тот самый обратный рывок при перетаскивании ползунка.

     stop() + start() клэмпа не делает: внутри обоих вызывается приватный
     reset(), который просто останавливает текущую анимацию и переписывает
     animatedScroll/targetScroll из actualScroll — того, что уже показывает
     браузер. Сам вызов ничего на экране не двигает и не обращается к
     lenis.limit вовсе.

     ownScrollUntil обновляет ТОЛЬКО markOwnScroll(). Раньше для этого был
     перехвачен сам instance.scrollTo, но Lenis вызывает его же и ИЗНУТРИ
     на каждое колесо мыши (wheel-обработчик делает
     `this.scrollTo(this.targetScroll + delta, {...})`), так что перехват
     продлевал «наше» окно на каждый тик колеса — и сторож не срабатывал,
     пока человек вообще крутил колесо, то есть ровно в том случае, ради
     которого он и написан. */
  let raf = 0;
  const loop = (time: number) => {
    const lenis = instance;
    if (lenis) {
      if (
        time > ownScrollUntil &&
        lenis.isScrolling === "smooth" &&
        Math.abs(window.scrollY - lenis.animatedScroll) > 2
      ) {
        lenis.stop();
        lenis.start();
      }
      lenis.raf(time);
    }
    raf = requestAnimationFrame(loop);
  };
  raf = requestAnimationFrame(loop);

  return () => {
    cancelAnimationFrame(raf);
    instance?.destroy();
    instance = null;
  };
}
