/**
 * Классы выравнивания для плитки ряда по её номеру.
 *
 * @param index порядковый номер плитки в ряду, с нуля
 */
export function stepTileZigzag(index: number): string {
  const side = index % 2 === 0 ? "max-md:justify-self-start" : "max-md:justify-self-end";
  return `max-md:w-[88%] ${side}`;
}
