import { useRef } from "react";

/* ═══════════ ЛИСТАНИЕ ПАЛЬЦЕМ ═══════════

   Один приём на все карусели сайта: отзывы на главной, ролики на «О нас».
   Держим его здесь, а не копией в каждом файле — пороги и правило «что
   считать листанием» должны быть одинаковыми везде, иначе на одной
   карусели палец срабатывает, а на соседней нет, и это читается как
   поломка. */

/** Насколько далеко надо провести пальцем, чтобы это засчиталось за
    листание, а не за дрожание руки при обычном тапе. */
export const SWIPE = 48;

/**
 * Горизонтальный свайп по блоку. Возвращает готовые обработчики —
 * разложить их в JSX через `{...useSwipe(fn)}`.
 *
 * Вертикальное движение намеренно пропускаем мимо: карточки высокие, и
 * палец по ним чаще ведут, чтобы прокрутить страницу. Если считать
 * листанием любое движение, карусель будет перескакивать на каждой
 * попытке прокрутки.
 *
 * Слушателей вешаем без оглядки на ширину экрана: touch-события приходят
 * только с сенсорного ввода, поэтому на десктопе этот код молчит сам, и
 * отдельного брейкпоинта ему не нужно.
 *
 * @param onSwipe вызывается с 1 при движении справа налево (вперёд) и −1
 *                при движении слева направо (назад)
 */
export function useSwipe(onSwipe: (dir: 1 | -1) => void) {
  const from = useRef<{ x: number; y: number } | null>(null);

  return {
    onTouchStart: (e: React.TouchEvent) => {
      const t = e.touches[0];
      from.current = { x: t.clientX, y: t.clientY };
    },
    onTouchEnd: (e: React.TouchEvent) => {
      const start = from.current;
      from.current = null;
      if (!start) return;
      const t = e.changedTouches[0];
      const dx = t.clientX - start.x;
      const dy = t.clientY - start.y;
      if (Math.abs(dx) < SWIPE || Math.abs(dx) < Math.abs(dy)) return;
      onSwipe(dx < 0 ? 1 : -1);
    },
  };
}
