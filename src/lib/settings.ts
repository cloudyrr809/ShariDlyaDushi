/** Ключ единственной строки таблицы. */
const ROW_ID = "main";

type Row = {
  id: string;
  delivery: string[] | null;
  payment: string[] | null;
  returns: string[] | null;
  care: string[] | null;
};

/** Пустые списки заменяем значениями по умолчанию: раздел без текста на
    сайте выглядит как забытая заготовка. */
const pick = (v: string[] | null | undefined, fallback: string[]) =>
  v && v.length > 0 ? v : fallback;

const fromRow = (r: Row): Settings => ({
  delivery: pick(r.delivery, defaultSettings.delivery),
  payment: pick(r.payment, defaultSettings.payment),
  returns: pick(r.returns, defaultSettings.returns),
  care: pick(r.care, defaultSettings.care),
});

const clean = (list: string[]) => list.map((s) => s.trim()).filter(Boolean);

/**
 * Читает условия. Возвращает значения по умолчанию во всех случаях, когда
 * настоящих взять неоткуда: база не подключена, строки ещё нет, сеть не
 * ответила. Условия доставки и возврата — не то, что можно показать
 * пустым местом, поэтому здесь нет ни `null`, ни исключений.
 */
export async function fetchSettings(): Promise<Settings> {
  if (!supabase) return defaultSettings;

  const { data, error } = await supabase
    .from("settings")
    .select("*")
    .eq("id", ROW_ID)
    .maybeSingle();

  if (error || !data) return defaultSettings;
  return fromRow(data as Row);
}

export async function saveSettings(s: Settings): Promise<void> {
  if (!supabase) throw new Error("База не подключена");
  const { error } = await supabase.from("settings").upsert({
    id: ROW_ID,
    delivery: clean(s.delivery),
    payment: clean(s.payment),
    returns: clean(s.returns),
    care: clean(s.care),
  });
  if (error) throw error;
}
